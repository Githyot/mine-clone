//! Monster health and damage by stage of the progression (plan/vida-dos-mobs.md).
//!
//! Every monster belongs to one of the six stages of the balance sheet (balance.rs) and has a
//! role in it: weak, normal, strong, elite, mini-boss or boss. The stage says what weapons and
//! armour the player has when they meet it; the role says how long it should take to kill and
//! how many of its hits the player can take:
//! - a normal monster dies in `TTK` seconds to the stage's target damage per second, and takes
//!   `HITS` of its blows to kill a player wearing the best armour of the stage;
//! - the other roles are multiples of that (`Role::hp`, `Role::atk`);
//! - a boss lasts its own number of seconds against the damage of the stage it is fought in.
//!
//! The mob files keep their own numbers (they are regenerated by tools, and the classic ones
//! are checked against Minecraft in parity_test.rs). `apply` rewrites the loaded definitions
//! once, keeping each monster's own character: its old numbers are pulled into the band of
//! its role (`KEEP`), not replaced by one flat value. The classic Minecraft monsters of the
//! first stages keep their numbers exactly, and the option "Força dos monstros: Clássica"
//! turns the whole thing off.

use voxel::mob::{MobDef, MobRegistry};

/// Seconds a normal monster lasts against the stage's target damage per second: a zombie (20)
/// against the iron sword (9) at the start, a little longer later when fights move more.
pub const TTK: [f32; 6] = [2.2, 2.4, 2.6, 2.8, 3.0, 3.2];

/// Blows of a normal monster a player with the stage's best armour can take (a zombie on a
/// player in lead armour at the start).
#[cfg(test)]
pub const HITS: [f32; 6] = [21.0, 14.0, 12.0, 11.0, 10.0, 9.0];

/// The player's health by each stage: 20 at the start, life crystals up to 40 before the
/// World Breaker, life fruit up to 50 after the mechanical bosses.
#[cfg(test)]
pub const PLAYER_HP: [f32; 6] = [20.0, 28.0, 36.0, 40.0, 46.0, 50.0];

/// Attack of a normal monster of each stage (worked out from `HITS`, `PLAYER_HP` and the best
/// defense of the stage; the test `hits_match` keeps it honest). The first one is the zombie's.
/// These are the files' numbers: in hardmode the game makes every hit `HARD_HIT` harder.
pub const ATTACK: [f32; 6] = [3.0, 10.0, 15.5, 13.0, 19.5, 25.0];

/// Monster health and damage multipliers the game already adds in hardmode (hardmode.rs gives
/// monsters 1.6 times their health, terraria.rs makes every hit 1.5 times harder). The table
/// is written for the numbers the player meets, so hardmode stages store less.
pub const HARD_HP: f32 = 1.6;
pub const HARD_HIT: f32 = 1.5;

/// How far a monster's own number may stay from its role's (0.8 = 20% under).
pub const KEEP: (f32, f32) = (0.8, 1.25);

#[derive(Clone, Copy, PartialEq, Debug)]
pub enum Role {
    /// A Minecraft monster: keeps the numbers of the original game.
    Classic,
    /// Bats, small jellies, eyes, swarms.
    Weak,
    Normal,
    /// Brutes, golems, big beasts.
    Strong,
    /// Rare and dangerous: mutant beasts, giant tortoises, wyverns.
    Elite,
    /// Rare monsters with a boss's weight but no boss bar: mimics, the moon's trees, ogres.
    Mini,
    /// A boss: seconds the fight lasts against the stage's target damage.
    Boss(f32),
    /// A link of a worm: the same as its head (damage to links goes to the head).
    Link(&'static str),
}

impl Role {
    /// Health of the role as a multiple of a normal monster's.
    pub fn hp(self) -> f32 {
        match self {
            Role::Weak => 0.5,
            Role::Strong => 2.0,
            Role::Elite => 4.0,
            Role::Mini => 15.0,
            _ => 1.0,
        }
    }

    /// Attack as a multiple of a normal monster's.
    pub fn atk(self) -> f32 {
        match self {
            Role::Weak => 0.7,
            Role::Strong => 1.3,
            Role::Elite => 1.6,
            Role::Mini => 2.0,
            // Bosses hit often (fans of bolts, charges), so each hit is lighter.
            Role::Boss(_) => 1.5,
            _ => 1.0,
        }
    }

    #[cfg(test)]
    pub fn name(self) -> &'static str {
        match self {
            Role::Classic => "clássico",
            Role::Weak => "fraco",
            Role::Normal => "normal",
            Role::Strong => "forte",
            Role::Elite => "elite",
            Role::Mini => "mini-chefe",
            Role::Boss(_) => "chefe",
            Role::Link(_) => "segmento",
        }
    }
}

