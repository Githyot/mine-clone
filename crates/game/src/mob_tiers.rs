/// Monsters that are not fought: guardians that only scare you away, traps, worm links that
/// can't be hurt (their head takes it all).
#[cfg(test)]
pub const UNTOUCHED: &[&str] = &["dungeon_guardian", "deep_worm_body", "deep_worm_tail", "mech_worm_body", "mech_worm_tail"];

pub fn tier(name: &str) -> Option<(u8, Role)> {
    TIERS.iter().find(|t| t.0 == name).map(|t| (t.1, t.2))
}

/// Health of a normal monster of `stage`, as the player meets it.
pub fn normal_hp(stage: u8) -> f32 {
    DPS[stage as usize] * TTK[stage as usize]
}

/// What a monster's health and attack become: its own numbers pulled into the band of its
/// role. `None` keeps the numbers of the file.
pub fn staged(def: &MobDef, stage: u8, role: Role, head: Option<(f32, f32)>) -> Option<(f32, f32)> {
    let s = stage as usize;
    let hard = s >= 3;
    let pull = |own: f32, want: f32| if own > 0.0 { own.clamp(want * KEEP.0, want * KEEP.1) } else { own };
    match role {
        Classic => None,
        Link(_) => head,
        Boss(secs) => {
            // Bosses get no hardmode health (their hits do get harder, as `ATTACK` counts).
            let hp = DPS[s] * secs;
            let atk = ATTACK[s] * role.atk();
            Some((pull(def.health, hp), pull(def.attack, atk)))
        }
        _ => {
            let hp = normal_hp(stage) * role.hp() / if hard { HARD_HP } else { 1.0 };
            let atk = ATTACK[s] * role.atk();
            Some((pull(def.health, hp), pull(def.attack, atk)))
        }
    }
}

/// The original numbers of the monsters `apply` changed, to put back for the classic option.
pub type Original = Vec<(usize, f32, f32)>;

/// Rewrites the loaded monsters' health and attack by stage. Returns what it changed.
pub fn apply(reg: &mut MobRegistry) -> Original {
    let mut old = Vec::new();
    // Heads first, so links can copy them.
    let mut new: Vec<Option<(f32, f32)>> = vec![None; reg.defs.len()];
    for (i, d) in reg.defs.iter().enumerate() {
        if let Some((stage, role)) = tier(&d.name).filter(|t| !matches!(t.1, Link(_))) {
            new[i] = staged(d, stage, role, None);
        }
    }
    for (i, d) in reg.defs.iter().enumerate() {
        if let Some((stage, role @ Link(head))) = tier(&d.name) {
            let h = reg.id(head).and_then(|h| new[h].or(Some((reg.defs[h].health, reg.defs[h].attack))));
            // A link bites a little less than the head.
            new[i] = staged(d, stage, role, h.map(|(hp, atk)| (hp, if d.attack > 0.0 { atk * 0.75 } else { 0.0 })));
        }
    }
    for (i, n) in new.into_iter().enumerate() {
        if let Some((hp, atk)) = n {
            let d = &mut reg.defs[i];
            old.push((i, d.health, d.attack));
            d.health = hp;
            d.attack = atk;
        }
    }
    old
}

/// Puts the file's numbers back.
pub fn restore(reg: &mut MobRegistry, old: &Original) {
    for &(i, hp, atk) in old {
        if let Some(d) = reg.defs.get_mut(i) {
            d.health = hp;
            d.attack = atk;
        }
    }
}

/// Is this a monster the table should know about?
#[cfg(test)]
pub fn is_monster(d: &MobDef) -> bool {
    d.kind == voxel::mob::Kind::Hostile && !UNTOUCHED.contains(&d.name.as_str())
}

/// Damage left after armour of `points` (survival.rs `armor_absorb`, then rpg.rs `rpg_reduce`).
#[cfg(test)]
pub fn after_armour(points: f32) -> f32 {
    (1.0 - points.min(20.0) * 0.04) * (1.0 - (points - 20.0).max(0.0) * 0.02).max(0.5)
}

