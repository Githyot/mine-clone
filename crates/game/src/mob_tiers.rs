    fn items() -> voxel::item::ItemRegistry {
        crate::game_data(crate::embedded::BLOCKS_RON, crate::embedded::ITEMS_RON, crate::embedded::RECIPES_RON).unwrap().1
    }

    /// Hits of `atk` a player of `stage` with its best armour takes, at Normal difficulty.
    fn hits(items: &voxel::item::ItemRegistry, stage: u8, atk: f32) -> f32 {
        let (def, _) = crate::balance::best_defense(items, stage);
        let hard = if stage >= 3 { HARD_HIT } else { 1.0 };
        PLAYER_HP[stage as usize] / (atk * hard * after_armour(def))
    }

    /// Health the player meets (hardmode adds its own to monsters that aren't bosses).
    fn met_hp(d: &MobDef, stage: u8) -> f32 {
        d.health * if stage >= 3 && !d.boss { HARD_HP } else { 1.0 }
    }

