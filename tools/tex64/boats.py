"""One boat per wood: its own model and its own skin.

Every boat is the wood's planks laid along the hull (the grain and marks of woods.py), and each
wood adds a trait of its own to the model: a keel and high sides for spruce, two seats on the
light birch boat, prow posts for jungle, an outrigger for acacia, thick iron-banded sides for
dark oak, curled posts for cherry, roots hugging the mangrove hull, a rudder on the pale oak boat.

This script writes both halves so they always agree:
* packs/vanilla/textures/entity/boat_<wood>.png, at 4 texels per model pixel (256 x 512);
* the `boat_<wood>` models in packs/vanilla/mobs.ron, between the "boats.py" marker comments.

    python3 tools/tex64/boats.py        (build.py runs it too)
"""

import os
import re

import numpy as np
from PIL import Image

import woods
from style import mix, ramp, rng_for, to_u8, value_noise

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
PACK = os.path.join(ROOT, "packs", "vanilla")
S = 4  # texels per model pixel
W, H = 64, 128  # skin layout in model pixels

BEGIN = "    // boats.py: one boat model per wood (generated by tools/tex64/boats.py, keep in sync)\n"
END = "    // end boats.py\n"

DISPLAY = {
    "oak": "Carvalho", "spruce": "Pinheiro", "birch": "Bétula", "jungle": "Selva", "acacia": "Acácia",
    "dark_oak": "Carvalho Escuro", "cherry": "Cerejeira", "mangrove": "Mangue", "pale_oak": "Carvalho Pálido",
}


def hull(side_h=6, side_w=2, end_d=2, floor=True):
    """The common rowing boat: floor, two long sides, bow and stern boards."""
    x = 6 + side_w
    parts = []
    if floor:
        parts.append(("hull", (12, 2, 20), (-6, 0, -10)))
    parts += [
        ("hull", (side_w, side_h, 22), (-x, 1, -11)),
        ("hull", (side_w, side_h, 22), (6, 1, -11)),
        ("hull", (12, side_h, end_d), (-6, 1, 11 - end_d)),
        ("hull", (12, side_h, end_d), (-6, 1, -11)),
    ]
    return parts


SEAT = ("seat", (12, 1, 3), (-6, 4, -1))

# wood -> (parts, plank board widths in texels (sum 64), extra paint)
BOATS = {
    "oak": dict(parts=hull() + [SEAT], boards=[8] * 8),
    "spruce": dict(parts=hull(side_h=7) + [("seat", (12, 1, 3), (-6, 5, -1)), ("keel", (2, 2, 24), (-1, -1, -12))],
                   boards=[11, 10, 11, 11, 10, 11]),
    "birch": dict(parts=hull(side_h=5) + [("seat", (12, 1, 3), (-6, 3, -6)), ("seat", (12, 1, 3), (-6, 3, 4))],
                  boards=[11, 10, 11, 11, 10, 11]),
    "jungle": dict(parts=hull() + [SEAT, ("post", (2, 10, 2), (-1, 1, 11)), ("post", (2, 10, 2), (-1, 1, -13))],
                   boards=[11, 10, 11, 11, 10, 11]),
    "acacia": dict(parts=hull() + [SEAT, ("arm", (14, 1, 2), (8, 5, -7)), ("arm", (14, 1, 2), (8, 5, 5)),
                                   ("float", (3, 3, 18), (20, 1, -9))],
                   boards=[8] * 8),
    "dark_oak": dict(parts=hull(side_h=7, side_w=3, end_d=3) + [("seat", (12, 1, 3), (-6, 5, -1))],
                     boards=[16] * 4, bands=True),
    "cherry": dict(parts=hull() + [SEAT, ("post", (2, 9, 2), (-1, 1, 11)), ("curl", (2, 2, 3), (-1, 8, 12)),
                                   ("post", (2, 9, 2), (-1, 1, -13)), ("curl", (2, 2, 3), (-1, 8, -15))],
                   boards=[8] * 8, petals=True),
    "mangrove": dict(parts=hull() + [SEAT, ("root", (18, 1, 2), (-9, -1, -7)), ("root", (18, 1, 2), (-9, -1, 4)),
                                     ("rootup", (1, 6, 2), (-9, 0, -7)), ("rootup", (1, 6, 2), (8, 0, -7)),
                                     ("rootup", (1, 6, 2), (-9, 0, 4)), ("rootup", (1, 6, 2), (8, 0, 4))],
                     boards=[13, 13, 12, 13, 13]),
    "pale_oak": dict(parts=hull() + [SEAT, ("rudder", (1, 7, 4), (0, -2, -15)), ("tiller", (1, 1, 5), (0, 5, -15))],
                     boards=[16] * 4, patches=True),
}


def faces(size, uv):
    """Minecraft-style box unwrap (as entity.rs reads it): face -> (x, y, w, h, u axis, v axis)."""
    w, h, d = size
    u, v = uv
    return {
        "top": (u + d, v, w, d, "x", "z"),
        "bottom": (u + d + w, v, w, d, "x", "z"),
        "right": (u, v + d, d, h, "z", "y"),
        "front": (u + d, v + d, w, h, "x", "y"),
        "left": (u + d + w, v + d, d, h, "z", "y"),
        "back": (u + 2 * d + w, v + d, w, h, "x", "y"),
    }


def pack(parts):
    """Shelf-pack every distinct box size into the layout (no relief layers, so all of it is free)."""
    sizes = []
    for _, sz, _ in parts:
        if sz not in sizes:
            sizes.append(sz)
    order = sorted(sizes, key=lambda s: -(s[2] + s[1]))
    uv = {}
    x = y = shelf = 0
    for sz in order:
        w, h, d = sz
        fw, fh = 2 * d + 2 * w, d + h
        if x + fw > W:
            x, y = 0, y + shelf
            shelf = 0
        uv[sz] = (x, y)
        x += fw
        shelf = max(shelf, fh)
        assert y + fh <= H and fw <= W, f"boat skin overflow at {sz}"
    return uv


def plank_tile(wood, boards):
    p = dict(woods.WOODS[wood])
    p.update(layout="rows", sizes=boards, joints=1)
    p["marks"] = {k: v for k, v in p["marks"].items() if k not in ("nails", "screws")}
    return woods.planks_with(wood, p, f"{wood}_boat_planks")[..., :3]


def bark_tile(wood):
    img = woods.bark(wood, f"{wood}_boat_bark")
    return img[..., :3]


def paint_face(skin, tile, x, y, fw, fh, along_u, rng, shade=1.0):
    X0, Y0, FW, FH = x * S, y * S, fw * S, fh * S
    if FW == 0 or FH == 0:
        return
    t = tile if along_u else np.transpose(tile, (1, 0, 2))
    ox, oy = rng.integers(0, 64, 2)
    yy = (np.arange(FH)[:, None] + oy) % 64
    xx = (np.arange(FW)[None, :] + ox) % 64
    region = t[yy, xx] * shade
    # Darker rim so each box reads as a solid piece.
    e = np.minimum.outer(np.minimum(np.arange(FH), FH - 1 - np.arange(FH)), np.minimum(np.arange(FW), FW - 1 - np.arange(FW)))
    region = region * np.where(e < 1, 0.78, np.where(e < 2, 0.9, 1.0))[..., None]
    skin[Y0:Y0 + FH, X0:X0 + FW, :3] = region
    skin[Y0:Y0 + FH, X0:X0 + FW, 3] = 255


def make(wood):
    spec = BOATS[wood]
    rng = rng_for(f"boat:{wood}")
    planks = plank_tile(wood, spec["boards"])
    bark = bark_tile(wood) if woods.WOODS[wood]["bark"] not in (None, "birch") else planks * 0.8
    if wood == "birch":
        bark = woods_birch_bark()
    uv = pack(spec["parts"])
    skin = np.zeros((H * S, W * S, 4))
    pal = ramp(woods.colours(wood)[0], 12, 0.36, 0.12)
    for role, sz, _ in spec["parts"]:
        tile = bark if role in ("float", "root", "rootup", "post") and wood in ("acacia", "mangrove", "jungle") else planks
        longest = "xyz"[int(np.argmax(sz))]
        for face, (x, y, fw, fh, ua, va) in faces(sz, uv[sz]).items():
            shade = {"top": 1.08, "bottom": 0.78}.get(face, 1.0)
            if role == "keel":
                shade *= 0.8
            paint_face(skin, tile, x, y, fw, fh, along_u=(ua == longest) or (va != longest and ua != "y"), rng=rng, shade=shade)
            X0, Y0, FW, FH = x * S, y * S, fw * S, fh * S
            # Rim of the sides: the lighter, worn top edge.
            if role == "hull" and face == "top":
                skin[Y0:Y0 + FH, X0:X0 + FW, :3] = mix(skin[Y0:Y0 + FH, X0:X0 + FW, :3], pal[9], 0.25)
            if spec.get("bands") and role == "hull" and face in ("right", "left") and sz[2] > 10:
                metal = ramp("#4a4744", 6, 0.3, 0.06)
                for bz in (3, 11, 18):
                    bx = X0 + bz * S
                    skin[Y0:Y0 + FH, bx:bx + 4, :3] = metal[2]
                    skin[Y0:Y0 + FH, bx:bx + 1, :3] = metal[4]
                    skin[Y0:Y0 + FH, bx + 3:bx + 4, :3] = metal[0]
                    for ry in range(Y0 + 3, Y0 + FH - 2, 8):
                        skin[ry:ry + 2, bx + 1:bx + 3, :3] = metal[5]
            if spec.get("patches") and role == "hull" and face in ("right", "left") and sz[2] > 10:
                lighter = ramp(mix(woods.colours(wood)[0], np.array([200.0, 198, 190]), 0.3), 8, 0.25, 0.08)
                for _ in range(2):
                    pw, ph = int(rng.integers(12, 20)), min(FH - 4, int(rng.integers(8, 14)))
                    px, py = X0 + int(rng.integers(2, FW - pw - 2)), Y0 + int(rng.integers(2, max(3, FH - ph - 1)))
                    n = value_noise(rng, 4)[:ph, :pw]
                    skin[py:py + ph, px:px + pw, :3] = lighter[np.clip((3 + n * 3).astype(int), 0, 7)]
                    skin[py:py + ph, px, :3] = lighter[1]
                    skin[py + ph - 1, px:px + pw, :3] = lighter[1]
                    for cx, cy in ((px + 1, py + 1), (px + pw - 3, py + 1), (px + 1, py + ph - 3), (px + pw - 3, py + ph - 3)):
                        skin[cy:cy + 2, cx:cx + 2, :3] = (90, 86, 80)
            if spec.get("petals") and face == "top" and role in ("hull", "seat"):
                petal = ramp("#f0a8c8", 6, 0.25, 0.1)
                for _ in range(max(1, fw * fh // 10)):
                    px, py = X0 + int(rng.integers(0, FW - 2)), Y0 + int(rng.integers(0, FH - 2))
                    skin[py:py + 2, px:px + 2, :3] = petal[int(rng.integers(2, 6))]
    skin[..., :3] = np.clip(skin[..., :3], 0, 255)
    return skin, uv


def woods_birch_bark():
    from blocks import log_side
    return log_side("birch", "birch_boat_bark")[..., :3]


def ron_block(models):
    out = [BEGIN]
    for wood, (spec, uv) in models.items():
        out.append("    (\n")
        out.append(f'        name: "boat_{wood}", display_name: "Barco de {DISPLAY[wood]}", kind: Passive, health: 6, speed: 0.0,\n')
        out.append("        width: 1.4, height: 0.6, spawn: Never,\n")
        out.append("        parts: [\n")
        for role, sz, org in spec["parts"]:
            u, v = uv[sz]
            out.append(f"            (size: {sz}, origin: {org}, uv: ({u}, {v})), // {role}\n".replace(" ,", ","))
        out.append("        ],\n        layers: [],\n    ),\n")
    out.append(END)
    return "".join(out)


def write_models(models):
    path = os.path.join(PACK, "mobs.ron")
    src = open(path, encoding="utf-8").read()
    block = ron_block(models)
    if BEGIN in src:
        src = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, src, flags=re.S)
    else:
        anchor = '    // Not a creature: windmill sails'
        assert anchor in src
        src = src.replace(anchor, block + anchor, 1)
    open(path, "w", encoding="utf-8").write(src)


def main():
    models = {}
    for wood in BOATS:
        skin, uv = make(wood)
        Image.fromarray(to_u8(skin), "RGBA").save(os.path.join(PACK, "textures", "entity", f"boat_{wood}.png"), optimize=True)
        models[wood] = (BOATS[wood], uv)
    write_models(models)
    print(f"boats: {len(models)} wood boats (skins + models)")


if __name__ == "__main__":
    main()
