def hard_ore(metal):
    p = METALS[metal]
    bg = gt.stone(metal + "_ore_stone")
    return gt.ore(metal, bg=bg, p=p[[1, 2, 4]])


def metal_block(metal):
    return gt.metal_block(metal + "_block", p6(METALS[metal]), facets=metal in ("verdite", "lumite"))


