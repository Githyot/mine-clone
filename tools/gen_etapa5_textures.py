def bone_spectral():
    img = gi.bone()
    rgb = img[..., :3].astype(int)
    m = img[..., 3] > 0
    rgb[m] = (rgb[m] * np.array([0.6, 0.85, 1.1])).clip(0, 255)
    img[..., :3] = rgb.astype(np.uint8)
    return img


